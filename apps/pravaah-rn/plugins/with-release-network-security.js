/**
 * Release builds must still be able to reach a plain-HTTP dev backend.
 *
 * The Expo Android template only grants cleartext HTTP in the DEBUG source set
 * (`android/app/src/debug/AndroidManifest.xml` sets
 * `android:usesCleartextTraffic="true"`). A release APK therefore inherits the
 * Android 9+ default of "TLS only" and every call to
 * `EXPO_PUBLIC_API_URL=http://<lan-ip>:8000` fails — the app installs, launches,
 * and then dies at the first request with a bare network error. That failure is
 * invisible at build time, which is exactly why this plugin exists.
 *
 * The blunt fix is `usesCleartextTraffic=true` app-wide. This is a financial
 * app, so we don't do that. Instead we emit a network security config that
 * keeps cleartext FORBIDDEN by default and re-permits it for exactly the hosts
 * a developer build needs: loopback, the Android emulator's host alias, and the
 * host named by EXPO_PUBLIC_API_URL when (and only when) that URL is http://.
 *
 * The attribute is written into a RELEASE-ONLY manifest rather than the main
 * one. `networkSecurityConfig` overrides `usesCleartextTraffic` on API 24+, so
 * putting it in the main manifest would also clamp DEBUG builds to this host
 * list — and the dev-client's Metro connection would then break the moment the
 * machine's LAN IP changed. Release-only keeps that dev loop permissive.
 */

const { withDangerousMod } = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

const RESOURCE_NAME = 'network_security_config';

/**
 * Hosts allowed to speak cleartext in a release build.
 * Loopback, the emulator's host alias, and ALL RFC 1918 private subnets are
 * included so that any LAN IP works without regenerating the config every time
 * the developer's network changes. The configured API host is also added
 * explicitly if it is served over http://.
 *
 * Android's network_security_config supports wildcards via `includeSubdomains`,
 * but for raw IP addresses we must list each /8 or /12 prefix. Since Android
 * does not support CIDR notation in domain entries, we whitelist the common
 * private ranges by their first octet patterns. For the 172.16-31.x.x range
 * we list each individual first two octets.
 */
function cleartextHosts() {
  const hosts = new Set(['localhost', '127.0.0.1', '10.0.2.2']);

  // All RFC 1918 private network prefixes — covers any LAN/hotspot IP.
  // 10.0.0.0/8
  hosts.add('10.*.*.*');
  // 192.168.0.0/16
  hosts.add('192.168.*.*');
  // 172.16.0.0/12 — Android domain entries don't support CIDR, so we list
  // each /16 subnet individually.
  for (let i = 16; i <= 31; i++) {
    hosts.add(`172.${i}.*.*`);
  }

  const apiUrl = process.env.EXPO_PUBLIC_API_URL;
  if (apiUrl) {
    try {
      const { protocol, hostname } = new URL(apiUrl);
      if (protocol === 'http:' && hostname) hosts.add(hostname);
    } catch {
      // A malformed EXPO_PUBLIC_API_URL is the app's problem to report at
      // runtime, not a reason to fail the build.
    }
  }

  return [...hosts];
}

/** Writes res/xml/network_security_config.xml into the main source set. */
function withNetworkSecurityResource(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const xmlDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      await fs.promises.mkdir(xmlDir, { recursive: true });

      const domains = cleartextHosts()
        .map((host) => `    <domain includeSubdomains="false">${host}</domain>`)
        .join('\n');

      const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-release-network-security.js — do not edit by hand. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="true">
    <trust-anchors>
      <certificates src="system" />
    </trust-anchors>
  </base-config>
</network-security-config>
`;

      await fs.promises.writeFile(path.join(xmlDir, `${RESOURCE_NAME}.xml`), xml, 'utf8');
      return cfg;
    },
  ]);
}

/** Points the release source set at that resource. */
function withReleaseManifest(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const releaseDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'release');
      await fs.promises.mkdir(releaseDir, { recursive: true });

      const manifest = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-release-network-security.js — do not edit by hand. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools">
    <application
        android:networkSecurityConfig="@xml/${RESOURCE_NAME}"
        tools:targetApi="24" />
</manifest>
`;

      await fs.promises.writeFile(path.join(releaseDir, 'AndroidManifest.xml'), manifest, 'utf8');
      return cfg;
    },
  ]);
}

module.exports = function withReleaseNetworkSecurity(config) {
  return withReleaseManifest(withNetworkSecurityResource(config));
};
