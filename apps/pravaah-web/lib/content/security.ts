/**
 * Security content.
 *
 * `SECURITY_FEATURES` is the load-bearing idea of this site: a banknote's
 * anti-forgery vocabulary maps one-to-one onto how this credential resists
 * forgery. Each entry pairs the printed feature with the real mechanism, so
 * the visual world is explaining the product rather than dressing it.
 *
 * The per-feature `status` field is gone, and its removal is the honest edit
 * rather than a tidy-up: every mechanism below is now built, so eight identical
 * badges said nothing while implying the reader should be scanning for the ones
 * that are not. Stage is stated once, for the whole product, in `STAGE`
 * (lib/config/site.ts). What remains genuinely uneven is which regulated rail
 * is live, and that is not a property of a note feature.
 */

export interface SecurityFeature {
  /** The feature as it appears on a printed note. */
  printed: string;
  /** What it does on the note. */
  onTheNote: string;
  /** The product mechanism it corresponds to. */
  mechanism: string;
  /** How that mechanism actually works. */
  detail: string;
}

